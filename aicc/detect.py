"""Find where each known AI tool is installed on this computer."""
import fnmatch
import os
import re
import shutil
import time
from pathlib import Path

from .catalog import APPIMAGE_DIRS, CATALOG, ORDER
from .util import HOME, expand, find_executable, run

USER_UNIT_DIR = Path(os.environ.get("XDG_CONFIG_HOME") or (HOME / ".config")) / "systemd" / "user"
SKIP_DIRS = {"node_modules", "venv", "site-packages", "__pycache__", "snap", "proc",
             "Trash", "go", "miniconda3", "anaconda3", "Steam", "Videos", "Music", "Pictures"}


def user_unit_name(service_id):
    return "ai-{}.service".format(service_id)


# ---------- Docker ----------

def docker_containers():
    """List all containers as dicts, or return (None, error message)."""
    if not shutil.which("docker"):
        return None, "Docker no está instalado."
    r = run(["docker", "ps", "-a", "--format",
             '{{.Names}}\t{{.Image}}\t{{.Label "com.docker.compose.project"}}\t{{.State}}'], timeout=8)
    if not r["ok"]:
        err = (r["err"] or r["out"]).lower()
        if "permission denied" in err:
            return None, ("Tu usuario no tiene permiso para usar Docker. Ejecutá "
                          "'sudo usermod -aG docker $USER' y volvé a iniciar sesión.")
        if "docker.sock" in err or "daemon" in err:
            return None, "Docker está instalado pero no está en ejecución."
        return None, "No se pudo consultar Docker: " + (r["err"] or r["out"] or "error desconocido")
    items = []
    for line in r["out"].splitlines():
        parts = line.split("\t")
        if len(parts) >= 2:
            items.append({"name": parts[0], "image": parts[1],
                          "project": parts[2] if len(parts) > 2 else "",
                          "state": parts[3] if len(parts) > 3 else ""})
    return items, None


def _match_docker(spec, containers):
    names = spec.get("docker_names", [])
    images = spec.get("docker_images", [])
    for c in containers:
        if c["name"] in names:
            return c
    for c in containers:
        if any(i in c["image"] for i in images):
            return c
    return None


# ---------- systemd ----------

def systemd_unit_exists(unit, user=False):
    args = ["systemctl"] + (["--user"] if user else []) + ["show", "-p", "LoadState", unit]
    r = run(args)
    return r["ok"] and r["out"].strip() == "LoadState=loaded"


def parse_unit(path):
    """Read WorkingDirectory/ExecStart from a user unit we may adopt."""
    info = {}
    try:
        text = Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return info
    home = str(HOME)
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("WorkingDirectory="):
            info["cwd"] = line.split("=", 1)[1].replace("%h", home)
        elif line.startswith("ExecStart="):
            info["exec"] = line.split("=", 1)[1].replace("%h", home).split()
    m = re.search(r"--port\s+(\d+)", text)
    if m:
        info["port"] = int(m.group(1))
    info["generated"] = "Generated by AI Control Center" in text
    return info


# ---------- folders (ComfyUI and similar) ----------

def valid_dir(path, markers):
    p = expand(path)
    return p.is_dir() and all((p / m).exists() for m in markers)


def python_for_dir(path):
    p = expand(path)
    for c in (p / "venv", p / ".venv", p.parent / "venv", p.parent / ".venv"):
        py = c / "bin" / "python"
        if py.exists():
            return str(py)
    return shutil.which("python3") or "/usr/bin/python3"


def scan_home(names, markers, max_depth=4, time_limit=2.5, max_results=5):
    """Breadth-first search in the home folder for directories named like names."""
    found = []
    deadline = time.time() + time_limit
    queue = [(HOME, 0)]
    lower_names = {n.lower() for n in names}
    while queue and time.time() < deadline and len(found) < max_results:
        current, depth = queue.pop(0)
        try:
            entries = list(os.scandir(str(current)))
        except OSError:
            continue
        for e in entries:
            try:
                if not e.is_dir(follow_symlinks=False):
                    continue
            except OSError:
                continue
            if e.name.startswith(".") or e.name in SKIP_DIRS:
                continue
            if e.name.lower() in lower_names and valid_dir(e.path, markers):
                found.append(e.path)
                continue
            if depth + 1 < max_depth:
                queue.append((Path(e.path), depth + 1))
    return found


_scan_cache = {}


def _home_dirs_by_name():
    """One walk of the home folder for all catalog folder names (cached per detection run)."""
    if "dirs" not in _scan_cache:
        names = {n.lower() for spec in CATALOG.values() for n in spec.get("dir_names", [])}
        _scan_cache["dirs"] = scan_home(names, [], max_depth=4, time_limit=4, max_results=60)
    return _scan_cache["dirs"]


def dir_candidates(spec):
    found = []
    for p in spec.get("dir_search", []) + ["~/" + n for n in spec.get("dir_names", [])]:
        if valid_dir(p, spec["dir_markers"]):
            rp = str(expand(p).resolve())
            if rp not in found:
                found.append(rp)
    names = {n.lower() for n in spec.get("dir_names", [])}
    for p in _home_dirs_by_name():
        if Path(p).name.lower() in names and valid_dir(p, spec["dir_markers"]):
            rp = str(Path(p).resolve())
            if rp not in found:
                found.append(rp)
    return found


# ---------- desktop apps ----------

def flatpak_apps():
    if not shutil.which("flatpak"):
        return set()
    r = run(["flatpak", "list", "--app", "--columns=application"], timeout=10)
    return set(r["out"].split()) if r["ok"] else set()


def deb_package(path):
    r = run(["dpkg", "-S", str(path)])
    return r["out"].split(":", 1)[0] if r["ok"] and ":" in r["out"] else None


def app_candidates(spec, flatpaks=None):
    """[(location dict)] for a desktop app, best match first."""
    found = []
    for raw in spec.get("app_paths", []):
        p = expand(raw)
        if p.is_file() and os.access(str(p), os.X_OK):
            pkg = deb_package(p)
            found.append({"type": "app", "source_kind": "deb" if pkg else "binary", "path": str(p), "package": pkg})
    globs = [g.lower() for g in spec.get("appimage_globs", [])]
    images = []
    for d in APPIMAGE_DIRS if globs else []:
        try:
            entries = list(os.scandir(str(expand(d))))
        except OSError:
            continue
        for e in entries:
            if e.is_file() and any(fnmatch.fnmatch(e.name.lower(), g) for g in globs):
                images.append((e.stat().st_mtime, e.path))
    for _mtime, path in sorted(images, reverse=True):  # newest download first
        found.append({"type": "app", "source_kind": "appimage", "path": path})
    for fid in spec.get("flatpak_ids", []):
        if fid in (flatpaks if flatpaks is not None else flatpak_apps()):
            found.append({"type": "app", "source_kind": "flatpak", "flatpak_id": fid, "path": "flatpak " + fid})
    return found


# ---------- main entry points ----------

def detect_service(service_id, docker_cache=None):
    """Return (location or None, candidates, notes) for one service."""
    spec = CATALOG[service_id]
    candidates = []
    notes = []
    for method in spec["detect"]:
        if method == "systemd":
            for unit in spec.get("systemd_units", []):
                if systemd_unit_exists(unit):
                    return {"type": "systemd", "unit": unit, "source": "auto"}, candidates, notes
        elif method == "docker":
            if docker_cache is None:
                docker_cache = docker_containers()
            containers, err = docker_cache
            if err:
                notes.append(err)
                continue
            c = _match_docker(spec, containers)
            if c:
                return {"type": "docker", "container": c["name"], "source": "auto"}, candidates, notes
        elif method == "binary":
            path = find_executable(spec.get("binaries", []), spec.get("binary_dirs", []))
            if path:
                return {"type": "process", "kind": "binary", "path": path,
                        "port": spec.get("binary_port", spec["port"]),
                        "unit_name": user_unit_name(service_id), "source": "auto"}, candidates, notes
        elif method == "legacy_unit":
            for unit in spec.get("legacy_units", []):
                unit_path = USER_UNIT_DIR / unit
                if unit_path.exists():
                    info = parse_unit(unit_path)
                    cwd = info.get("cwd")
                    if cwd and valid_dir(cwd, spec["dir_markers"]):
                        py = info.get("exec", [None])[0] or python_for_dir(cwd)
                        return {"type": "process", "kind": "dir", "path": cwd, "python": py,
                                "port": info.get("port", spec["port"]), "unit_name": unit,
                                "source": "auto"}, candidates, notes
        elif method == "app":
            apps = app_candidates(spec, _scan_cache.get("flatpaks"))
            if apps:
                candidates = [a["path"] for a in apps]
                return dict(apps[0], port=spec["port"], source="auto"), candidates, notes
        elif method == "dir":
            candidates = dir_candidates(spec)
            if candidates:
                path = candidates[0]
                return {"type": "process", "kind": "dir", "path": path, "python": python_for_dir(path),
                        "port": spec["port"], "unit_name": user_unit_name(service_id),
                        "source": "auto"}, candidates, notes
    return None, candidates, notes


def detect_all():
    _scan_cache.clear()
    _scan_cache["flatpaks"] = flatpak_apps()
    docker_cache = docker_containers()
    results = {}
    for sid in [s for s in ORDER if not CATALOG[s].get("custom")]:
        loc, candidates, notes = detect_service(sid, docker_cache)
        results[sid] = {"location": loc, "candidates": candidates, "notes": notes}
    return results


def validate_manual(service_id, payload):
    """Turn what the user typed in the "indicar ruta" dialog into a location.

    Returns (location, None) or (None, error message).
    """
    spec = CATALOG[service_id]
    kind = payload.get("type")
    port = payload.get("port") or None
    if port is not None:
        try:
            port = int(port)
            if not 1 <= port <= 65535:
                raise ValueError
        except (TypeError, ValueError):
            return None, "El puerto debe ser un número entre 1 y 65535."

    if kind == "docker":
        if "docker" not in spec["detect"]:
            return None, "Este servicio no se ejecuta con Docker."
        name = str(payload.get("container") or "")
        containers, err = docker_containers()
        if err:
            return None, err
        if name not in {c["name"] for c in containers}:
            return None, "No existe un contenedor llamado '{}'.".format(name)
        return {"type": "docker", "container": name, "source": "manual"}, None

    if kind == "path":
        raw = str(payload.get("path") or "").strip()
        if not raw:
            return None, "Indicá una ruta."
        p = expand(raw)
        if not p.is_absolute():
            return None, "Usá una ruta absoluta, por ejemplo /home/usuario/ComfyUI."
        if "dir_markers" in spec:
            if p.is_file():
                p = p.parent
            if not valid_dir(p, spec["dir_markers"]):
                return None, "No parece una carpeta válida: falta {}.".format(" o ".join(spec["dir_markers"]))
            py = str(payload.get("python") or "").strip()
            if py:
                py_path = expand(py)
                if not (py_path.is_file() and os.access(str(py_path), os.X_OK)):
                    return None, "El Python indicado no existe o no es ejecutable."
                py = str(py_path)
            else:
                py = python_for_dir(p)
            return {"type": "process", "kind": "dir", "path": str(p.resolve()), "python": py,
                    "port": port or spec["port"], "unit_name": user_unit_name(service_id),
                    "source": "manual"}, None
        if "binaries" in spec:
            if not (p.is_file() and os.access(str(p), os.X_OK)):
                return None, "El archivo no existe o no es ejecutable."
            return {"type": "process", "kind": "binary", "path": str(p),
                    "port": port or spec.get("binary_port", spec["port"]),
                    "unit_name": user_unit_name(service_id), "source": "manual"}, None
        if "app" in spec["detect"]:
            if not (p.is_file() and os.access(str(p), os.X_OK)):
                return None, "El archivo no existe o no es ejecutable (si es un AppImage, dale permiso de ejecución)."
            kind = "appimage" if p.name.lower().endswith(".appimage") else "binary"
            pkg = deb_package(p) if kind == "binary" else None
            return {"type": "app", "source_kind": "deb" if pkg else kind, "path": str(p), "package": pkg,
                    "port": port or spec["port"], "source": "manual"}, None
        return None, "Este servicio no se instala desde una ruta; elegí un contenedor Docker."
    return None, "Tipo de ubicación no válido."
