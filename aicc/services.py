"""Status, start/stop and login autostart for each configured service."""
import json
import os
import shutil
import subprocess
from pathlib import Path

from . import metrics
from .catalog import CATALOG
from .detect import USER_UNIT_DIR, parse_unit
from .util import port_open, run

HELPER_DIR = Path(__file__).resolve().parent.parent / "helpers"
ACTIONS = {"start", "stop", "restart"}
UNIT_MARKER = "# Generated by AI Control Center"


# ---------- privileged helpers (only for the Ollama system service) ----------

def _installed_helper(name):
    """Return the helper path only if it is root-owned, i.e. installed by the .deb."""
    p = HELPER_DIR / name
    try:
        st = p.stat()
    except OSError:
        return None
    return str(p) if st.st_uid == 0 and shutil.which("pkexec") else None


def root_systemctl(action, unit):
    """Run systemctl as root for an allowlisted system unit.

    Tries the sudoers rule from the old install.sh first, then the polkit helper
    shipped with the .deb (no password for start/stop/enable/disable).
    """
    r = run(["sudo", "-n", "systemctl", action, unit], timeout=30)
    if r["ok"]:
        return r
    helper = _installed_helper("aicc-service-helper")
    if helper:
        r = run(["pkexec", helper, action, unit], timeout=60)
        if r["ok"]:
            return r
    if not r["err"]:
        r["err"] = "No hay permisos para controlar {} sin contraseña.".format(unit)
    return r


# ---------- user units for tools run from a folder or an executable ----------

def _quote(arg):
    arg = str(arg).replace("%", "%%").replace("$", "$$")
    if any(c in arg for c in ' "\\\t'):
        return '"' + arg.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return arg


def unit_content(service_id, loc):
    spec = CATALOG[service_id]
    port = str(loc.get("port") or spec["port"])
    lines = ["[Unit]", "Description={} (AI Control Center)".format(spec["label"]),
             "After=network.target", UNIT_MARKER, "", "[Service]", "Type=simple"]
    if loc.get("kind") == "dir":
        template = spec["dir_command"]
        for marker, alt in spec.get("dir_command_if", {}).items():
            if (Path(loc["path"]) / marker).exists():
                template = alt
        cmd = [a.replace("{python}", loc.get("python") or "python3").replace("{dir}", loc["path"]).replace("{port}", port)
               for a in template]
        lines.append("WorkingDirectory=" + _quote(loc["path"]))
    else:
        cmd = [a.replace("{bin}", loc["path"]).replace("{port}", port) for a in spec["binary_command"]]
        for k, v in spec.get("binary_env", {}).items():
            lines.append("Environment=" + _quote("{}={}".format(k, v.replace("{port}", port))))
    lines += ["ExecStart=" + " ".join(_quote(a) for a in cmd),
              "Environment=PYTHONUNBUFFERED=1", "Restart=on-failure", "RestartSec=5", "",
              "[Install]", "WantedBy=default.target", ""]
    return "\n".join(lines)


def ensure_user_unit(service_id, loc, force=False):
    """Write the user unit unless the user maintains their own version of it."""
    path = USER_UNIT_DIR / loc["unit_name"]
    if path.exists() and not force and not parse_unit(path).get("generated"):
        return  # adopted unit written by hand or by the old install.sh
    USER_UNIT_DIR.mkdir(parents=True, exist_ok=True)
    content = unit_content(service_id, loc)
    try:
        if path.read_text(encoding="utf-8") == content:
            return
    except OSError:
        pass
    path.write_text(content, encoding="utf-8")
    run(["systemctl", "--user", "daemon-reload"])


def _user_unit_state(unit):
    r = run(["systemctl", "--user", "is-active", unit])
    return r["out"] or "inactive"


def _is_enabled(unit, user):
    r = run(["systemctl"] + (["--user"] if user else []) + ["is-enabled", unit])
    return r["out"] in ("enabled", "enabled-runtime", "static", "alias")


# ---------- Docker ----------

def docker_inspect(names):
    if not names or not shutil.which("docker"):
        return []
    r = run(["docker", "inspect"] + list(names), timeout=8)
    try:
        return json.loads(r["out"]) if r["out"] else []
    except ValueError:
        return []


def docker_group(container):
    """Main container info plus every container of the same compose project."""
    info = docker_inspect([container])
    if not info:
        return None, []
    main = info[0]
    project = (main.get("Config", {}).get("Labels") or {}).get("com.docker.compose.project")
    names = [container]
    if project:
        r = run(["docker", "ps", "-a", "--filter", "label=com.docker.compose.project=" + project,
                 "--format", "{{.Names}}"], timeout=8)
        if r["ok"] and r["out"]:
            names = r["out"].splitlines()
    return main, names


def _docker_port(main, default):
    for _key, binds in sorted((main.get("HostConfig", {}).get("PortBindings") or {}).items()):
        for b in binds or []:
            if b.get("HostPort"):
                return int(b["HostPort"])
    return default


# ---------- desktop apps (AppImage, .deb, Flatpak) ----------

AUTOSTART_DIR = Path(os.environ.get("XDG_CONFIG_HOME") or (Path.home() / ".config")) / "autostart"


def app_command(loc):
    if loc.get("source_kind") == "flatpak":
        return ["flatpak", "run", loc["flatpak_id"]]
    return [loc["path"]]


def app_processes(spec, loc):
    try:
        import psutil
    except ImportError:
        return []
    names = {n.lower() for n in spec.get("process_names", [])}
    path = (loc.get("path") or "").lower()
    path_match = (spec.get("process_path_match") or "").lower()
    flatpak_id = (loc.get("flatpak_id") or "").lower()
    me = os.getuid()
    found = []
    for proc in psutil.process_iter(["pid", "name", "cmdline", "uids"]):
        try:
            if proc.info["uids"] and proc.info["uids"].real != me:
                continue
            name = (proc.info["name"] or "").lower()
            cmd = " ".join(proc.info["cmdline"] or []).lower()
            if (path and loc.get("source_kind") != "flatpak" and path in cmd) or (flatpak_id and flatpak_id in cmd):
                found.append(proc)
            elif loc.get("source_kind") == "appimage" and name in names:
                found.append(proc)
            elif name in names and (not path_match or path_match in cmd):
                found.append(proc)
        except (psutil.NoSuchProcess, psutil.AccessDenied):
            continue
    return found


def _autostart_file(service_id):
    return AUTOSTART_DIR / "aicc-{}.desktop".format(service_id)


def _app_start(service_id, loc):
    try:
        subprocess.Popen(app_command(loc), stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                         stderr=subprocess.DEVNULL, start_new_session=True, cwd=str(Path.home()))
        return {"ok": True, "out": "", "err": "", "code": 0}
    except OSError as e:
        return {"ok": False, "out": "", "err": str(e), "code": -1}


def _app_stop(service_id, loc):
    import psutil
    procs = app_processes(CATALOG[service_id], loc)
    for p in procs:
        try:
            p.terminate()
        except psutil.Error:
            pass
    _gone, alive = psutil.wait_procs(procs, timeout=8)
    for p in alive:
        try:
            p.kill()
        except psutil.Error:
            pass
    return {"ok": True, "out": "", "err": "", "code": 0}


# ---------- public API ----------

def describe_location(loc):
    if not loc:
        return ""
    if loc["type"] == "systemd":
        return "Servicio del sistema " + loc["unit"]
    if loc["type"] == "docker":
        return "Contenedor Docker " + loc["container"]
    if loc["type"] == "app":
        kinds = {"appimage": "AppImage", "deb": "Paquete .deb", "flatpak": "Flatpak", "binary": "Programa"}
        return "{} · {}".format(kinds.get(loc.get("source_kind"), "App"), loc.get("path", ""))
    return loc["path"]


def status(service_id, loc, with_metrics=True):
    spec = CATALOG[service_id]
    out = {"id": service_id, "name": spec["label"], "icon": spec["icon"], "description": spec["description"],
           "installed": bool(loc), "location": describe_location(loc), "source": (loc or {}).get("source"),
           "type": (loc or {}).get("type"), "state": "not-installed", "running": False,
           "url": None, "port": None, "autostart": None, "metrics": dict(metrics.EMPTY),
           "manual_hint": spec.get("manual_hint", ""), "accepts_docker": "docker" in spec["detect"],
           "accepts_path": any(m in spec["detect"] for m in ("binary", "dir", "legacy_unit", "app")),
           "custom": bool(spec.get("custom")), "web": spec.get("web", True), "homepage": spec.get("homepage")}
    if not loc:
        return out

    port = loc.get("port") or spec["port"]
    m = dict(metrics.EMPTY)
    if loc["type"] == "systemd":
        r = run(["systemctl", "is-active", loc["unit"]])
        state = r["out"] or "inactive"
        out["autostart"] = _is_enabled(loc["unit"], user=False)
        if with_metrics and state == "active":
            m = metrics.process_metrics(process_names=spec.get("process_names"))
    elif loc["type"] == "docker":
        main, names = docker_group(loc["container"])
        if main is None:
            state = "missing"
        else:
            state = main.get("State", {}).get("Status", "unknown")
            policy = main.get("HostConfig", {}).get("RestartPolicy", {}).get("Name", "")
            out["autostart"] = policy in ("always", "unless-stopped")
            port = _docker_port(main, port)
            out["containers"] = names
            if with_metrics and state == "running":
                m = metrics.docker_metrics(names)
    elif loc["type"] == "app":
        exists = loc.get("source_kind") == "flatpak" or Path(loc.get("path", "")).exists()
        procs = app_processes(spec, loc) if exists else []
        state = "missing" if not exists else ("running" if procs else "inactive")
        out["autostart"] = _autostart_file(service_id).exists()
        if with_metrics and procs:
            m = metrics.pids_metrics(procs)
    else:
        if not Path(loc["path"]).exists():
            state = "missing"
        else:
            state = _user_unit_state(loc["unit_name"])
            if state != "active" and port_open(port):
                state = "external"  # running, but started outside the panel
            out["autostart"] = _is_enabled(loc["unit_name"], user=True)
            if with_metrics and state in ("active", "external"):
                if loc.get("kind") == "dir":
                    m = metrics.process_metrics(cmdline_contains=spec.get("cmdline_match", []), cwd=loc["path"])
                else:
                    m = metrics.process_metrics(process_names=spec.get("process_names") or [Path(loc["path"]).name])
    out.update(state=state, running=state in ("active", "running", "external"), port=port,
               url="http://127.0.0.1:{}".format(port), metrics=m)
    return out


def control(service_id, loc, action):
    """Start, stop or restart. Returns (ok, message)."""
    spec = CATALOG[service_id]
    if action not in ACTIONS:
        return False, "Operación no permitida."
    if loc["type"] == "systemd":
        r = root_systemctl(action, loc["unit"])
    elif loc["type"] == "docker":
        _main, names = docker_group(loc["container"])
        if not names:
            return False, "El contenedor {} ya no existe.".format(loc["container"])
        r = run(["docker", action] + names, timeout=90)
    elif loc["type"] == "app":
        if action in ("stop", "restart"):
            _app_stop(service_id, loc)
        r = _app_start(service_id, loc) if action in ("start", "restart") else {"ok": True}
    else:
        if action != "start" and _user_unit_state(loc["unit_name"]) != "active" and port_open(loc.get("port")):
            return False, "{} se inició fuera del panel; detenelo desde donde lo abriste.".format(spec["label"])
        ensure_user_unit(service_id, loc)
        r = run(["systemctl", "--user", action, loc["unit_name"]], timeout=30)
    if not r["ok"]:
        return False, r["err"] or r["out"] or "La operación falló."
    verbs = {"start": "iniciando", "stop": "deteniendo", "restart": "reiniciando"}
    return True, "{}: {}…".format(spec["label"], verbs[action])


def set_autostart(service_id, loc, enabled):
    """Enable or disable starting the service when the user logs in."""
    spec = CATALOG[service_id]
    if loc["type"] == "systemd":
        r = root_systemctl("enable" if enabled else "disable", loc["unit"])
    elif loc["type"] == "docker":
        _main, names = docker_group(loc["container"])
        if not names:
            return False, "El contenedor ya no existe."
        r = run(["docker", "update", "--restart", "unless-stopped" if enabled else "no"] + names, timeout=30)
    elif loc["type"] == "app":
        f = _autostart_file(service_id)
        try:
            if enabled:
                AUTOSTART_DIR.mkdir(parents=True, exist_ok=True)
                f.write_text("[Desktop Entry]\nType=Application\nName={}\nExec={}\nTerminal=false\n"
                             "X-GNOME-Autostart-enabled=true\n# Generated by AI Control Center\n".format(
                                 spec["label"], " ".join(_quote(a) for a in app_command(loc))), encoding="utf-8")
            elif f.exists():
                f.unlink()
            r = {"ok": True}
        except OSError as e:
            r = {"ok": False, "err": str(e), "out": ""}
    else:
        ensure_user_unit(service_id, loc)
        r = run(["systemctl", "--user", "enable" if enabled else "disable", loc["unit_name"]], timeout=15)
    if not r["ok"]:
        return False, r["err"] or r["out"] or "No se pudo cambiar el inicio automático."
    if enabled:
        return True, "{} se iniciará al iniciar sesión.".format(spec["label"])
    return True, "{} ya no se iniciará al iniciar sesión.".format(spec["label"])


def remove_app_autostart(service_id):
    try:
        _autostart_file(service_id).unlink()
    except OSError:
        pass


def remove_user_unit(loc):
    unit = loc.get("unit_name")
    if not unit:
        return
    run(["systemctl", "--user", "disable", "--now", unit], timeout=30)
    try:
        os.remove(str(USER_UNIT_DIR / unit))
    except OSError:
        pass
    run(["systemctl", "--user", "daemon-reload"])
